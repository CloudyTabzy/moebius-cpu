"""Count Moebius UNet / VAE FLOPs on the meta device (no weights, no RAM).

Also writes the expected state-dict manifest (name, shape) that
tools/convert_weights.py validates checkpoints against.

    python tools/count_flops.py [--manifest docs/weights-manifest.txt]

Needs torch, diffusers, timm, einops, pyyaml and a Moebius source checkout
(default ../Moebius, override with MOEBIUS_SRC).
"""
import argparse, builtins, collections, os, sys, types

import torch, yaml
from torch.utils.flop_counter import FlopCounterMode

MOE = os.environ.get("MOEBIUS_SRC", os.path.join(os.path.dirname(__file__), "..", "..", "Moebius"))
sys.path.insert(0, MOE)
# Skip model_lib/__init__.py: it imports the PixelHacker teacher, which needs
# flash-linear-attention (CUDA only).
pkg = types.ModuleType("model_lib"); pkg.__path__ = [os.path.join(MOE, "model_lib")]
sys.modules["model_lib"] = pkg

_print = builtins.print
builtins.print = lambda *a, **k: None  # the UNet constructor prints per block
from model_lib.nets.unet_lambda_prune_lite import \
    UNet2DLambdaDWConvMixFFNConditionModel_prune_down_mid_up_block_8x8 as UNet
from diffusers.models import AutoencoderKL

cfg = yaml.safe_load(open(os.path.join(MOE, "config/model_cfg/moebius.yaml")))
m = dict(cfg["model"]); m.pop("model_type"); m.update(sample_size=64, num_embeddings=20)
with torch.device("meta"):
    unet = UNet(**m).eval()
    embedding = torch.nn.Embedding(20, 3072)
    vae = AutoencoderKL(block_out_channels=(128, 256, 512, 512), layers_per_block=2,
                        down_block_types=("DownEncoderBlock2D",) * 4,
                        up_block_types=("UpDecoderBlock2D",) * 4, latent_channels=4).eval()
builtins.print = _print


def conv_kinds(model, run):
    acc = collections.Counter()

    def hook(mod, inp, out):
        o = out[0] if isinstance(out, tuple) else out
        k = mod.weight.shape
        macs = o.numel() * k[1] * k[2] * k[3] * (k[4] if len(k) == 5 else 1)
        if isinstance(mod, torch.nn.Conv3d): kind = "lambda pos_conv 15x15"
        elif mod.groups > 1: kind = f"depthwise {k[2]}x{k[3]}"
        elif k[2] == k[3] == 1: kind = "1x1 (GEMM)"
        elif max(mod.stride) > 1: kind = f"{k[2]}x{k[3]} stride 2"
        else: kind = f"{k[2]}x{k[3]} dense"
        acc[kind] += 2 * macs

    hooks = [mod.register_forward_hook(hook) for mod in model.modules()
             if isinstance(mod, (torch.nn.Conv2d, torch.nn.Conv3d))]
    fc = FlopCounterMode(display=False)
    with fc:
        run()
    for h in hooks: h.remove()
    total = fc.get_total_flops()
    print(f"  total {total / 1e9:8.1f} GFLOP")
    for kind, f in acc.most_common():
        print(f"    {kind:24s} {f / 1e9:8.1f} GFLOP  {100 * f / total:5.1f}%")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--manifest", help="write expected state-dict names/shapes here")
    args = ap.parse_args()

    n = lambda mod: sum(p.numel() for p in mod.parameters()) / 1e6
    print(f"UNet {n(unet):.1f}M params, VAE {n(vae):.1f}M params")
    with torch.no_grad():
        x = torch.randn(2, 9, 64, 64, device="meta")
        ehs = embedding(torch.arange(20, device="meta").view(2, 10))
        t = torch.tensor([500], device="meta")
        print("UNet step, batch 2 (CFG):")
        conv_kinds(unet, lambda: unet(x, timestep=t, encoder_hidden_states=ehs))
        print("VAE encode, batch 2 (image + masked image):")
        conv_kinds(vae, lambda: vae.encode(torch.randn(2, 3, 512, 512, device="meta")))
        print("VAE decode, batch 1:")
        conv_kinds(vae, lambda: vae.decode(torch.randn(1, 4, 64, 64, device="meta")))

    if args.manifest:
        with open(args.manifest, "w", encoding="utf-8", newline="\n") as f:
            f.write("# Expected checkpoint tensors (name<TAB>shape). Generated by tools/count_flops.py.\n")
            f.write("# [unet] keys are RemovalModel state-dict names (embedding_layer.*, diff_model.*).\n")
            f.write("[unet]\n")
            f.write(f"embedding_layer.weight\t{list(embedding.weight.shape)}\n")
            for k, v in unet.state_dict().items():
                f.write(f"diff_model.{k}\t{list(v.shape)}\n")
            f.write("[vae]\n")
            for k, v in vae.state_dict().items():
                f.write(f"{k}\t{list(v.shape)}\n")
        print(f"wrote {args.manifest}")


if __name__ == "__main__":
    main()
